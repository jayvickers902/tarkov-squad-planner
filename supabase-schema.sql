-- Tarkov Squad Planner foundational database bootstrap.
--
-- This file creates only the tables required by the ordered migrations. It is
-- intentionally deny-by-default: the parties, profile, and curated-data
-- tables have RLS enabled but no permissive policies here. The numbered
-- migrations install the current membership-scoped policies and RPCs.
--
-- New projects: run this file once, then run every supabase/10_*.sql file in
-- filename order. Do not treat this file as a complete application schema or
-- run it as a replacement for the numbered migrations.

-- Parties are session-scoped until 10_02 converts them to the current
-- membership-keyed shape. Keep the legacy columns here because 10_02 removes
-- them only after it has removed policies that depend on them.
create table if not exists public.parties (
  id         bigint generated by default as identity primary key,
  code       text unique not null,
  leader     text not null,
  map_id     text,
  map_name   text,
  map_norm   text,
  members    jsonb not null default '{}'::jsonb,
  spawn      text,
  progress   jsonb not null default '{}'::jsonb,
  starred    jsonb not null default '{}'::jsonb,
  drawings   jsonb not null default '[]'::jsonb,
  markers    jsonb not null default '[]'::jsonb,
  pings      jsonb not null default '[]'::jsonb,
  ping_log   jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

-- User quests — one row per saved quest per user. Later migrations add the
-- bounded constraints, canonical state transitions, and realtime publication.
create table if not exists public.user_quests (
  id               bigint generated by default as identity primary key,
  user_id          uuid references auth.users(id) on delete cascade not null,
  quest_id         text not null,
  quest_name       text not null,
  map_norm         text,
  important        boolean not null default false,
  skipped          boolean not null default false,
  obj_progress     jsonb not null default '{}'::jsonb,
  game_mode        text not null default 'regular'
    check (game_mode in ('regular', 'pve', 'pvp-season')),
  state            text not null default 'active'
    check (state in ('active', 'failed', 'completed')),
  state_at         timestamptz,
  state_source     text not null default 'manual'
    check (state_source in ('manual', 'log_import', 'live', 'system')),
  source_event_key text,
  created_at       timestamptz not null default now(),
  unique (user_id, game_mode, quest_id)
);

-- User profiles — callsign and administrator flag. Administrator data is not
-- readable until the policy/RPC migrations explicitly scope that access.
create table if not exists public.profiles (
  id         uuid references auth.users(id) on delete cascade primary key,
  callsign   text unique not null,
  is_admin   boolean not null default false,
  created_at timestamptz not null default now()
);

-- Curated reference data. The policy migrations decide which authenticated
-- users may read or administer these rows.
create table if not exists public.map_keys (
  id         bigint generated by default as identity primary key,
  map_norm   text not null,
  key_name   text not null,
  priority   boolean not null default false,
  loc_x      double precision,
  loc_y      double precision,
  updated_at timestamptz not null default now(),
  unique (map_norm, key_name)
);

create table if not exists public.map_loot (
  id         bigint generated by default as identity primary key,
  map_norm   text not null,
  loot_name  text not null,
  loot_type  text not null default 'document',
  loc_x      double precision,
  loc_y      double precision,
  notes      text,
  updated_at timestamptz not null default now(),
  unique (map_norm, loot_name, loc_x, loc_y)
);

create index if not exists map_loot_map_idx on public.map_loot (map_norm);

-- RLS is enabled before any client-facing policy exists. Running this file by
-- itself therefore cannot expose parties, profiles, or curated data across
-- accounts, and cannot create a party through direct table writes.
alter table public.parties     enable row level security;
alter table public.user_quests enable row level security;
alter table public.profiles   enable row level security;
alter table public.map_keys   enable row level security;
alter table public.map_loot   enable row level security;

-- User quest access is safe to establish at bootstrap and remains compatible
-- with the later migrations, which replace/extend these policies as needed.
drop policy if exists "User quests select" on public.user_quests;
drop policy if exists "User quests insert" on public.user_quests;
drop policy if exists "User quests update" on public.user_quests;
drop policy if exists "User quests delete" on public.user_quests;

create policy "User quests select" on public.user_quests
  for select using (auth.uid() = user_id);
create policy "User quests insert" on public.user_quests
  for insert with check (auth.uid() = user_id);
create policy "User quests update" on public.user_quests
  for update using (auth.uid() = user_id)
  with check (auth.uid() = user_id);
create policy "User quests delete" on public.user_quests
  for delete using (auth.uid() = user_id);
